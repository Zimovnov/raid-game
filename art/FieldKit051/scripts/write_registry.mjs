import fs from 'node:fs';
const registry=JSON.parse(fs.readFileSync('public/assets/field-kit-051/registry.json','utf8'));
// The two AK calibres are gameplay platforms, but render through one shared
// Blender body.  Keep the explicit key as well so ModelAssets can cache a
// single loaded container for both weapon definitions.
const runtimeRegistry={...registry};
if(runtimeRegistry.weapon_ak_common){
 runtimeRegistry.weapon_akm=runtimeRegistry.weapon_ak_common;
 runtimeRegistry.weapon_ak74m=runtimeRegistry.weapon_ak_common;
}
fs.writeFileSync('src/content/model-assets.ts','// Generated by art/FieldKit051; meshes follow the existing item/attachment tree.\nexport const MODEL_ASSETS: Record<string, { url: string; groups: string[] }> = '+JSON.stringify(runtimeRegistry,null,2)+';\n');

const {createHash}=await import('node:crypto');
const url=name=>'/assets/field-kit-051/'+name+'?v='+createHash('sha256').update(fs.readFileSync('public/assets/field-kit-051/'+name)).digest('hex').slice(0,12);
const fabrics=Object.fromEntries(fs.readdirSync('public/assets/field-kit-051').filter(n=>n.startsWith('camo-')&&n.endsWith('.png')).map(n=>[n.slice(5,-4),url(n)]));
fs.writeFileSync('src/content/fabric-assets.ts','// Original project fabric textures; content hashes prevent stale cached patterns.\nexport const FABRIC_ASSETS: Record<string,string> = '+JSON.stringify(fabrics,null,2)+';\nexport const FABRIC_NORMAL = '+JSON.stringify(url('fabric-normal.png'))+';\n');
